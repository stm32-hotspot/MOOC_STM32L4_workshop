#define STRLCD_SIZE 7
#define STRUART_SIZE 7
#define ADCBUF_SIZE 500
#define UARTBUF_SIZE (STRUART_SIZE-1)*ADCBUF_SIZE

#define TEMPSENSOR_TEMPREF 30  //reference value of temperature [C] in data sheet
#define ADCRESOLUTION 4095    //12-bit
#define ADCVREF 3.0           //ADC Vref [V]
#define TEMPSENSOR_VSLOPE 0.0025  //Internal temperature sensor slope [V/C]
#define TEMPSENSOR_VSLOPE_INT (uint16_t)(TEMPSENSOR_VSLOPE/(ADCVREF/ADCRESOLUTION))
#define TEMPSENSOR_V30 0.76  //Internal temperature sensor output voltage [V] for 30C according to data sheet
#define TEMPSENSOR_V30_INT  (uint16_t)(TEMPSENSOR_V30/(ADCVREF/ADCRESOLUTION))

int16_t adcbuf[ADCBUF_SIZE];
