int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration----------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_TIM2_Init();
  MX_USART2_UART_Init();

  /* USER CODE BEGIN 2 */
  
  BSP_LED_Init(LED4);  //BSP RED LED init (Error handler)
  BSP_LED_Init(LED5);  //BSP GREEN LED init (RUN mode indicator)
	
  BSP_LCD_GLASS_Init();
  
  HAL_ADCEx_Calibration_Start(&hadc1, ADC_SINGLE_ENDED);
  
  HAL_TIM_OC_Start(&htim2,TIM_CHANNEL_2);
  
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
  /* USER CODE END WHILE */

  /* USER CODE BEGIN 3 */
    
     snprintf((char*)str,STRLCD_SIZE,"RUN A ");			
     BSP_LCD_GLASS_DisplayString(str); 
     //BSP_LED_On(LED5);
     HAL_Delay(3000);
     //BSP_LED_Off(LED5);
     snprintf((char*)str,STRLCD_SIZE,"ADCDMA");			
     BSP_LCD_GLASS_DisplayString(str); 
  
     HAL_ADC_Start_DMA(&hadc1,(uint32_t*)adcbuf,ADCBUF_SIZE);
    
     HAL_SuspendTick(); 
     HAL_PWR_EnterSLEEPMode(PWR_MAINREGULATOR_ON, PWR_SLEEPENTRY_WFI);  
     HAL_PWR_EnterSLEEPMode(PWR_MAINREGULATOR_ON, PWR_SLEEPENTRY_WFI);  //because of HalfTransferComplete_DMA wakup
     HAL_ResumeTick();
      
     snprintf((char*)str,STRLCD_SIZE,"RUN B ");			
     BSP_LCD_GLASS_DisplayString(str);
     //BSP_LED_On(LED5);
     HAL_Delay(3000);
     //BSP_LED_Off(LED5);
     for(uint16_t i=0;i<ADCBUF_SIZE;i++)
     {
       adcbuf[i] = (adcbuf[i] - TEMPSENSOR_V30_INT)/TEMPSENSOR_VSLOPE_INT + TEMPSENSOR_TEMPREF;
       snprintf((char*)str,STRUART_SIZE,"%03d,\r\n",adcbuf[i]);
       for(uint16_t j=0;j<STRUART_SIZE-1;j++)
       {
         uartbuf[i*(STRUART_SIZE-1)+j]=str[j];
       }
     }
      
     snprintf((char*)str,STRLCD_SIZE,"USART ");			
     BSP_LCD_GLASS_DisplayString(str);  
      
     SystemClock_Decrease();
     MX_USART2_UART_Init();  //USART init after system clock decreasing
     HAL_UART_Transmit_DMA(&huart2, (uint8_t*)uartbuf, UARTBUF_SIZE);
      
     HAL_SuspendTick(); 
     HAL_PWR_EnterSLEEPMode(PWR_LOWPOWERREGULATOR_ON, PWR_SLEEPENTRY_WFI);
     HAL_PWR_EnterSLEEPMode(PWR_LOWPOWERREGULATOR_ON, PWR_SLEEPENTRY_WFI);  //because of HalfTransferComplete_DMA wakup
     HAL_ResumeTick();
      
     HAL_PWREx_DisableLowPowerRunMode();
     SystemClock_Config();  
  }
  /* USER CODE END 3 */

}

/** System Clock Configuration
*/
void SystemClock_Config(void)
{

  RCC_OscInitTypeDef RCC_OscInitStruct;
  RCC_ClkInitTypeDef RCC_ClkInitStruct;
  RCC_PeriphCLKInitTypeDef PeriphClkInit;

  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_MSI;
  RCC_OscInitStruct.MSIState = RCC_MSI_ON;
  RCC_OscInitStruct.MSICalibrationValue = 0;
  RCC_OscInitStruct.MSIClockRange = RCC_MSIRANGE_6;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_NONE;
  HAL_RCC_OscConfig(&RCC_OscInitStruct);

  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1|RCC_CLOCKTYPE_PCLK2;
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_MSI;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV1;
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV1;
  HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_0);

  PeriphClkInit.PeriphClockSelection = RCC_PERIPHCLK_USART2|RCC_PERIPHCLK_ADC;
  PeriphClkInit.Usart2ClockSelection = RCC_USART2CLKSOURCE_PCLK1;
  PeriphClkInit.AdcClockSelection = RCC_ADCCLKSOURCE_SYSCLK;
  HAL_RCCEx_PeriphCLKConfig(&PeriphClkInit);

  __PWR_CLK_ENABLE();

  HAL_PWREx_ControlVoltageScaling(PWR_REGULATOR_VOLTAGE_SCALE1);

  HAL_SYSTICK_Config(HAL_RCC_GetHCLKFreq()/1000);

  HAL_SYSTICK_CLKSourceConfig(SYSTICK_CLKSOURCE_HCLK);

}

