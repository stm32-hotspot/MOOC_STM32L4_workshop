void LOGGER_Serv(void)
{
  uint32_t adcbuf;
  uint8_t str[7];
  
  if (HAL_ADCEx_Calibration_Start(&hadc1, ADC_SINGLE_ENDED) != HAL_OK) {Error_Handler();};
  if (HAL_ADC_Start(&hadc1) != HAL_OK) {Error_Handler();}
  if (HAL_ADC_PollForConversion(&hadc1,100) != HAL_OK) {Error_Handler();}
  HAL_ADC_PollForConversion(&hadc1,100);
  adcbuf = HAL_ADC_GetValue(&hadc1);
  
  buf[bufptr] = adcbuf;
  
  BSP_LCD_GLASS_Init();
  snprintf((char*)str,7,"P:%04d",bufptr);
  BSP_LCD_GLASS_DisplayString(str); 
  HAL_Delay(1000);
  
  temperature = ((int16_t)adcbuf - TEMPSENSOR_V30_INT)/TEMPSENSOR_VSLOPE_INT + TEMPSENSOR_TEMPREF;
  snprintf((char*)str,STRLCD_SIZE,"%4d°C",temperature);
  BSP_LCD_GLASS_DisplayString(str);
  HAL_Delay(1000);
  BSP_LCD_GLASS_DeInit();
  
   if (bufptr<BUF_SIZE)
  {
    bufptr++;
  }
  buf[BUFPTR_ADD] = bufptr; 
}


